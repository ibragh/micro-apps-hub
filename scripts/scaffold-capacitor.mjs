#!/usr/bin/env node
// Generates apps/<slug>/capacitor.config.ts for every app in the manifest
// and adds @mofeed/mobile to its devDependencies. Idempotent: re-running
// updates the config (since it is generated) and is a no-op for the
// devDep if already present.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import { apps } from './apps.manifest.mjs';

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

function capacitorConfig(app) {
  return `/**
 * Capacitor configuration — auto-generated by scripts/scaffold-capacitor.mjs.
 *
 * One-time per app:
 *   pnpm --filter @mofeed/${app.slug} add -D @capacitor/cli @capacitor/core
 *   pnpm --filter @mofeed/${app.slug} add -D @capacitor/ios @capacitor/android
 *   cd apps/${app.slug}
 *   pnpm build
 *   npx cap add ios
 *   npx cap add android
 *
 * After every web rebuild:
 *   pnpm --filter @mofeed/${app.slug} build && cd apps/${app.slug} && npx cap sync
 *
 * Open ios/App.xcworkspace in Xcode or android/ in Android Studio to ship.
 */
import { defineMobileConfig } from '@mofeed/mobile';

const config = defineMobileConfig({
  appId: 'com.mofeed.${app.slug}',
  appName: ${JSON.stringify(app.nameAr)},
  webDir: 'dist',
});

export default config;
`;
}

async function addMobileDevDep(pkgPath) {
  const j = JSON.parse(await fs.readFile(pkgPath, 'utf8'));
  j.devDependencies = j.devDependencies || {};
  if (j.devDependencies['@mofeed/mobile'] === 'workspace:*') return false;
  j.devDependencies['@mofeed/mobile'] = 'workspace:*';
  // Keep the deps map alphabetised for diff readability.
  const entries = Object.entries(j.devDependencies).sort(([a], [b]) => a.localeCompare(b));
  j.devDependencies = Object.fromEntries(entries);
  await fs.writeFile(pkgPath, JSON.stringify(j, null, 2) + '\n');
  return true;
}

let written = 0;
let pkgUpdated = 0;
for (const app of apps) {
  const dir = path.join(root, 'apps', app.slug);
  await fs.writeFile(path.join(dir, 'capacitor.config.ts'), capacitorConfig(app));
  written++;
  if (await addMobileDevDep(path.join(dir, 'package.json'))) pkgUpdated++;
}
console.log(`Wrote ${written} capacitor.config.ts files; added @mofeed/mobile to ${pkgUpdated} package.json files.`);
